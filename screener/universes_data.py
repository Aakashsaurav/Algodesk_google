def _build_nifty_500() -> List[str]:
    seen: set[str] = set()
    out: List[str] = []
    for lst in (NIFTY_50, NIFTY_FNO_FALLBACK, _NIFTY_EXTENDED):
        for s in lst:
            clean = s.strip().upper()
            if clean and clean not in seen:
                seen.add(clean)
                out.append(clean)
    return out


NIFTY_500: List[str] = _build_nifty_500()
